#!/bin/bash
#
# detect-os.sh - which supported operating systems does the GRUB menu boot?
#
#   sudo ./detect-os.sh                 # analyse /boot/grub/grub.cfg
#   ./detect-os.sh --cfg FILE [-v]      # analyse any grub.cfg (no root needed)
#
# Read-only. Uses exactly the parser/classifier of the installed hook
# (grub.d/99_grub_icon_menu), so the answer matches what update-grub does.
# Output is machine readable (KEY=VALUE, shell-quoted), e.g.:
#   WINDOWS=1  TARGET_WINDOWS=osprober-efi-63A4-7C42  ENTRIES_WINDOWS=1
#              (gim-windows-handoff: started by the UEFI firmware)
#   LINUX=1    TARGET_LINUX=gnulinux-simple-...       ENTRIES_LINUX=5
#   KINDS='windows linux'  LAYOUT=windows-linux  FALLBACK_KIND=linux
#   KALI=1 TARGET_KALI=gim-kali-handoff ...   (other systems, when found)
#   MISSING_ICONS='fedora'                    (found, icon after update.sh)
# With -v the per-entry classification is printed to stderr.

set -Eeuo pipefail
PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

CFG="/boot/grub/grub.cfg"
VERBOSE=0
PLATFORM=""
while [ $# -gt 0 ]; do
    case "$1" in
        --cfg)      CFG="${2:-}"; shift 2 ;;
        --platform) PLATFORM="${2:-}"; shift 2 ;;
        -v|--verbose) VERBOSE=1; shift ;;
        -h|--help)  sed -n '3,15p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

if [ ! -r "$CFG" ]; then
    if [ -e "$CFG" ]; then
        echo "detect-os.sh: cannot read $CFG (it is root-only on Ubuntu): run with sudo" >&2
    else
        echo "detect-os.sh: $CFG not found" >&2
    fi
    exit 1
fi

GIM_HOOK_LIB=1
# shellcheck source=grub.d/99_grub_icon_menu
. "$PROJECT_DIR/grub.d/99_grub_icon_menu"
unset GIM_HOOK_LIB

gim_load_config || true
if [ -n "$PLATFORM" ]; then GIM_PLATFORM="$PLATFORM"; GIM_CPU="${GIM_CPU:-x86_64}"; fi
gim_detect_platform

# A grub.cfg generated by the hook says which icons it shows: classify every
# os-prober system (as the hook may have), then keep only those.
hook_kinds="$(sed -n 's/^# Detected (internal): \(.*\) - icons: .*/\1/p' "$CFG" | head -n1)"
if [ -n "$hook_kinds" ]; then GIM_FOREIGN_LINUX=true; fi
records="$(gim_parse <"$CFG")"
gim_classify <<<"$records"
# A grub.cfg generated by the hook: its own section (which gim_parse does not
# read) tells how the icons really boot - Windows and other systems through
# their firmware handoff entries (gim-<kind>-handoff) - and which icons are
# shown at all.
for k in $(grep -o -e '--id gim-[a-z0-9]*-handoff ' "$CFG" | sed 's/^--id gim-//; s/-handoff $//' | awk '!seen[$0]++'); do
    case " $GIM_ALL_KINDS " in *" $k "*) ;; *) continue ;; esac
    if [ "$k" = windows ]; then gim_use_handoff; else gim_use_firmware "$k" "" "" "$(gim_os_name "$k")"; fi
done
if [ -n "$hook_kinds" ]; then
    for k in $GIM_KINDS; do
        case " $hook_kinds " in *" $k "*) ;; *) gim_drop_kind "$k" ;; esac
    done
fi
GIM_MISSING_ICONS="$(sed -n 's/^# Detected without icon (run update.sh): //p' "$CFG" | head -n1)"
if [ "$VERBOSE" = 1 ]; then
    {
        echo "Menu entries in $CFG (platform: $GIM_PLATFORM):"
        gim_report
        echo
    } >&2
fi
gim_print_results
