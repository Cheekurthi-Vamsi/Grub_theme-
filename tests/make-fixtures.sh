#!/bin/bash
#
# tests/make-fixtures.sh - derive the scenario fixtures from the realistic
# base fixture (tests/fixtures/windows-ubuntu.cfg, modelled on the output of
# Ubuntu 26.04's /etc/grub.d scripts). Re-run after editing the base.

set -Eeuo pipefail
F="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/fixtures"
BASE="$F/windows-ubuntu.cfg"

# section NAME -> the "### BEGIN ... NAME ###" block of the base fixture
section() {
    awk -v n="$1" '
        $0 == "### BEGIN /etc/grub.d/" n " ###" { on = 1 }
        on { print }
        $0 == "### END /etc/grub.d/" n " ###" { on = 0 }' "$BASE"
}
# empty section with its markers
empty() { printf '### BEGIN /etc/grub.d/%s ###\n### END /etc/grub.d/%s ###\n\n' "$1" "$1"; }
header() { printf '# test fixture: %s (generated by tests/make-fixtures.sh)\n\n' "$1"; section 00_header; echo; section 05_debian_theme; echo; }

linux_entry() {   # linux_entry TITLE ID VERSION [INDENT]
    local t="$1" id="$2" v="$3" i="${4:-}"
    cat <<EOF
${i}menuentry '$t' --class ubuntu --class gnu-linux --class gnu --class os \$menuentry_id_option '$id' {
${i}	recordfail
${i}	load_video
${i}	insmod gzio
${i}	insmod part_gpt
${i}	insmod ext2
${i}	search --no-floppy --fs-uuid --set=root 1f97a033-564c-48d9-87a0-0b664bc2adad
${i}	linux	/vmlinuz-$v root=UUID=8c6f1b2e-3d4a-4f5b-9c6d-7e8f9a0b1c2d ro  quiet splash \$vt_handoff
${i}	initrd	/initrd.img-$v
${i}}
EOF
}
windows_entry() {   # windows_entry DEVICE UUID [EFIPATH]
    cat <<EOF
# This menu entry is supported only on EFI platforms.
if [ "\$grub_platform" = "efi" ]; then
menuentry 'Windows Boot Manager (on $1)' --class windows --class os \$menuentry_id_option 'osprober-efi-$2' {
	insmod part_gpt
	insmod fat
	search --no-floppy --fs-uuid --set=root $2
	chainloader ${3:-/efi/Microsoft/Boot/bootmgfw.efi}
}
fi
EOF
}
R=8c6f1b2e-3d4a-4f5b-9c6d-7e8f9a0b1c2d

# TEST 2: Ubuntu only (os-prober found nothing)
{ header "Ubuntu only"; section 10_linux; echo; section 20_memtest86+; echo
  empty 30_os-prober; section 30_uefi-firmware; echo; section 41_custom; } >"$F/ubuntu-only.cfg"

# Ubuntu + Linux Mint on another partition, found by os-prober (as
# 30_os-prober writes it: --class linuxmint from os-prober's label).
sed '/^### END \/etc\/grub.d\/30_os-prober ###$/i\
menuentry '"'"'Linux Mint 22.1 Xia (22.1) (on /dev/nvme0n1p6)'"'"' --class linuxmint --class gnu-linux --class gnu --class os $menuentry_id_option '"'"'osprober-gnulinux-simple-6666'"'"' {\
	insmod part_gpt\
	insmod ext2\
	search --no-floppy --fs-uuid --set=root 6666\
	linux /boot/vmlinuz-6.8.0-50-generic root=UUID=6666 ro quiet splash\
	initrd /boot/initrd.img-6.8.0-50-generic\
}' "$F/ubuntu-only.cfg" >"$F/ubuntu-mint.cfg"

# TEST 3: Windows only (no Linux kernel entries at all)
{ header "Windows only"; empty 10_linux
  echo "### BEGIN /etc/grub.d/30_os-prober ###"; windows_entry /dev/nvme0n1p1 63A4-7C42
  echo "### END /etc/grub.d/30_os-prober ###"; echo; section 30_uefi-firmware; } >"$F/windows-only.cfg"

# TEST 4: only unknown/unsupported entries: memtest, firmware setup, fwupd,
# another distribution found by os-prober, a BIOS-only chainloader, a custom
# entry. Expected: no chooser at all.
{ header "unknown entries only"; empty 10_linux; section 20_memtest86+; echo
  cat <<'EOF'
### BEGIN /etc/grub.d/30_os-prober ###
menuentry 'Arch Linux (on /dev/sda2)' --class arch --class gnu-linux --class gnu --class os $menuentry_id_option 'osprober-gnulinux-simple-1111' {
	insmod part_gpt
	insmod ext2
	search --no-floppy --fs-uuid --set=root 1111
	linux /boot/vmlinuz-linux root=/dev/sda2
	initrd /boot/initramfs-linux.img
}
# This menu entry is supported only on PC BIOS platforms.
if [ "$grub_platform" = "pc" ]; then
menuentry 'Windows 10 (on /dev/sda1)' --class windows --class os $menuentry_id_option 'osprober-chain-2222' {
	insmod part_msdos
	insmod ntfs
	search --no-floppy --fs-uuid --set=root 2222
	parttool ${root} hidden-
	drivemap -s (hd0) ${root}
	chainloader +1
}
fi
### END /etc/grub.d/30_os-prober ###

EOF
  section 30_uefi-firmware; echo
  cat <<'EOF'
### BEGIN /etc/grub.d/35_fwupd ###
menuentry 'Linux Firmware Updater' $menuentry_id_option 'fwupd' {
	insmod part_gpt
	insmod fat
	search --no-floppy --fs-uuid --set=root 63A4-7C42
	chainloader /EFI/ubuntu/fwupdx64.efi
}
### END /etc/grub.d/35_fwupd ###

### BEGIN /etc/grub.d/40_custom ###
menuentry "Reboot" {
	reboot
}
### END /etc/grub.d/40_custom ###
EOF
} >"$F/unknown-only.cfg"

# TEST 4b: Ubuntu plus the unknown entries above. Expected: Tux only.
{ header "Ubuntu + unknown entries"; section 10_linux; echo
  sed -n '/^### BEGIN \/etc\/grub.d\/20_memtest86+ ###$/,$p' "$F/unknown-only.cfg"; } >"$F/ubuntu-unknown.cfg"

# TEST 5: many kernels, GRUB_DISABLE_SUBMENU=true (every kernel top-level).
{ header "multiple Ubuntu kernels without submenu"
  echo "### BEGIN /etc/grub.d/10_linux ###"
  linux_entry 'Ubuntu, with Linux 7.0.0-40-generic' "gnulinux-7.0.0-40-generic-advanced-$R" 7.0.0-40-generic
  linux_entry 'Ubuntu, with Linux 7.0.0-40-generic (recovery mode)' "gnulinux-7.0.0-40-generic-recovery-$R" 7.0.0-40-generic
  linux_entry 'Ubuntu, with Linux 7.0.0-38-generic' "gnulinux-7.0.0-38-generic-advanced-$R" 7.0.0-38-generic
  linux_entry 'Ubuntu, with Linux 7.0.0-38-generic (recovery mode)' "gnulinux-7.0.0-38-generic-recovery-$R" 7.0.0-38-generic
  linux_entry 'Ubuntu, with Linux 7.0.0-34-generic' "gnulinux-7.0.0-34-generic-advanced-$R" 7.0.0-34-generic
  echo "### END /etc/grub.d/10_linux ###"; echo
  section 30_uefi-firmware; } >"$F/multi-kernel-flat.cfg"

# TEST 6: Windows (seen twice: two ESPs) + three kernels in a submenu.
{ header "Windows x2 + multiple Ubuntu kernels"
  echo "### BEGIN /etc/grub.d/10_linux ###"
  linux_entry 'Ubuntu' "gnulinux-simple-$R" 7.0.0-40-generic
  echo "submenu 'Advanced options for Ubuntu' \$menuentry_id_option 'gnulinux-advanced-$R' {"
  for v in 7.0.0-40-generic 7.0.0-38-generic 7.0.0-34-generic; do
      linux_entry "Ubuntu, with Linux $v" "gnulinux-$v-advanced-$R" "$v" $'\t'
      linux_entry "Ubuntu, with Linux $v (recovery mode)" "gnulinux-$v-recovery-$R" "$v" $'\t'
  done
  echo "}"
  echo "### END /etc/grub.d/10_linux ###"; echo
  section 20_memtest86+; echo
  echo "### BEGIN /etc/grub.d/30_os-prober ###"
  windows_entry /dev/nvme0n1p1 63A4-7C42
  windows_entry /dev/sda1 9ABC-DEF0 /EFI/Microsoft/Boot/bootmgfw.efi
  echo "### END /etc/grub.d/30_os-prober ###"; echo
  section 30_uefi-firmware; } >"$F/windows-multi-kernels.cfg"

echo "fixtures written to $F"
