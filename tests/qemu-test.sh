#!/bin/bash
#
# tests/qemu-test.sh - run the generated menu in REAL GRUB inside QEMU/OVMF.
#
#   tests/qemu-test.sh --fixture tests/fixtures/windows-ubuntu.cfg \
#       --theme DIR --out DIR [--resolution 1920x1080] [--default VALUE] \
#       [--cfg COMPLETE_GRUB_CFG [--strip-prefix PATH]] \
#       [--hook-env "VAR=VALUE ..."] [--timeout SECONDS] [--setting VAR=VALUE]... \
#       [--extra "GRUB SCRIPT run right after 00_header"] -- ACTION...
#
# --setting adds a line to the hook's settings drop-in (e.g.
# GRUB_ICON_MENU=false for the plain menu).
#
# ACTIONs (executed in order once QEMU is running):
#   wait:SECONDS      sleep
#   shot:NAME         screenshot to OUT/NAME.png
#   KEY               QEMU sendkey name (down, up, ret, esc, right, left, ...)
#
# What is real and what is simulated:
#   real      : GRUB 2.14 core and modules of this machine (grub-mkstandalone
#               uses /usr/lib/grub/x86_64-efi), the generated theme, chooser.cfg
#               and the grub.cfg snippet produced by grub.d/99_grub_icon_menu.
#   simulated : disks. Everything lives in GRUB's memdisk, `search` lines are
#               removed, and every linux/chainloader command is replaced by
#               gimtest_boot, which prints "GIMTEST-BOOTED chosen=<entry id>"
#               on the serial port instead of starting an OS.
#
# QEMU/OVMF need not be installed: point QEMU_ROOT at an extracted tree
# (apt-get download qemu-system-x86 ovmf-generic ... ; dpkg-deb -x).

set -Eeuo pipefail
HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "$HERE/.." && pwd)"

FIXTURE=""; THEME=""; OUT=""; RES="1920x1080"; DEFAULT=""; HOOK_ENV=""; TIMEOUT=30; EXTRA=""
FULLCFG=""; STRIP=""; SETTINGS=()
while [ $# -gt 0 ]; do
    case "$1" in
        --fixture)  FIXTURE="$2"; shift 2 ;;
        --theme)    THEME="$2"; shift 2 ;;
        --out)      OUT="$2"; shift 2 ;;
        --resolution) RES="$2"; shift 2 ;;
        --default)  DEFAULT="$2"; shift 2 ;;
        --hook-env) HOOK_ENV="$2"; shift 2 ;;
        --timeout)  TIMEOUT="$2"; shift 2 ;;
        --extra)    EXTRA="$2"; shift 2 ;;
        --setting)  SETTINGS+=("$2"); shift 2 ;;
        --cfg)      FULLCFG="$2"; shift 2 ;;
        --strip-prefix) STRIP="$2"; shift 2 ;;
        --) shift; break ;;
        *) echo "unknown option $1" >&2; exit 2 ;;
    esac
done
ACTIONS=("$@")
{ [ -f "$FIXTURE" ] || [ -f "$FULLCFG" ]; } && [ -d "$THEME" ] && [ -n "$OUT" ] \
    || { echo "need --fixture or --cfg, --theme, --out" >&2; exit 2; }

QEMU_ROOT="${QEMU_ROOT:-}"
if [ -n "$QEMU_ROOT" ]; then
    QEMU=(env LD_LIBRARY_PATH="$QEMU_ROOT/usr/lib/x86_64-linux-gnu" "$QEMU_ROOT/usr/bin/qemu-system-x86_64" -L "$QEMU_ROOT/usr/share/qemu")
    OVMF_CODE="$QEMU_ROOT/usr/share/OVMF/OVMF_CODE_4M.fd"
    OVMF_VARS="$QEMU_ROOT/usr/share/OVMF/OVMF_VARS_4M.fd"
else
    QEMU=(qemu-system-x86_64)
    OVMF_CODE=/usr/share/OVMF/OVMF_CODE_4M.fd
    OVMF_VARS=/usr/share/OVMF/OVMF_VARS_4M.fd
fi

mkdir -p "$OUT"
W="$(mktemp -d "${TMPDIR:-/tmp}/gim-qemu.XXXXXX")"
# Unix socket paths are limited to 108 bytes: keep the monitor socket short.
SOCKDIR="$(mktemp -d "${XDG_RUNTIME_DIR:-/tmp}/gimq.XXXXXX")"
SOCK="$SOCKDIR/mon"
QPID=""
cleanup() { [ -n "$QPID" ] && kill "$QPID" 2>/dev/null || true; rm -rf -- "$W" "$SOCKDIR"; }
trap cleanup EXIT

# ---- 1. grub.cfg = fixture + output of the real hook (test mode) ----------
#        (or, with --cfg, a complete grub.cfg generated by update-grub)
mkdir -p "$W/etc/default/grub.d"
cat >"$W/etc/default/grub.d/99-grub-icon-menu.cfg" <<EOF
GRUB_ICON_MENU=true
GRUB_ICON_MENU_THEME_DIR="$THEME"
GRUB_ICON_MENU_TIMEOUT=$TIMEOUT
EOF
if [ "${#SETTINGS[@]}" -gt 0 ]; then printf '%s\n' "${SETTINGS[@]}" >>"$W/etc/default/grub.d/99-grub-icon-menu.cfg"; fi
cfg="$W/grub.cfg"
if [ -n "$FULLCFG" ]; then
    if [ -n "$STRIP" ]; then sed "s|$STRIP||g" "$FULLCFG"; else cat "$FULLCFG"; fi >"$cfg"
else
{
    sed -e "s|^   set default=\"0\"$|   set default=\"${DEFAULT:-0}\"|" "$FIXTURE" |
        awk -v extra="$EXTRA" '{ print } /^### END \/etc\/grub.d\/00_header ###$/ && extra != "" { print extra }' 
    echo
    echo "### BEGIN /etc/grub.d/99_grub_icon_menu ###"
    # shellcheck disable=SC2086
    env $HOOK_ENV GIM_INPUT_CFG="$FIXTURE" GIM_SYSCONFDIR="$W/etc" \
        GIM_PLATFORM=efi GIM_CPU=x86_64 \
        GIM_TEST_DEVICE_PREP="" GIM_TEST_THEME_REL="/grub/themes/grub-icon-menu" \
        "$PROJECT_DIR/grub.d/99_grub_icon_menu"
    echo "### END /etc/grub.d/99_grub_icon_menu ###"
} >"$cfg"
fi
grub-script-check "$cfg"
cp "$cfg" "$OUT/grub.cfg.generated"

# ---- 2. adapt for the VM: no disks, observable "boot" ------------------------
vmcfg="$W/vm.cfg"
{
    cat <<'EOF'
function gimtest_boot {
  serial --unit=0 --speed=115200
  terminal_output --append serial
  echo "GIMTEST-BOOTED chosen=${chosen} default=${default}"
  sleep 3600
}
EOF
    fontlines="$(cd "$THEME" && for f in *.pf2; do [ -f "$f" ] && printf 'loadfont ($root)/grub/themes/grub-icon-menu/%s\\n' "$f"; done)"
    sed -E \
        -e 's/^([[:space:]]*)search[[:space:]]+--no-floppy.*/\1true/' \
        -e "s/^([[:space:]]*)set root='[^']*'\$/\1set root=memdisk/" \
        -e '/^loadfont \(\$root\)\/grub\/themes\//d' \
        -e "s|^insmod gfxmenu\$|insmod gfxmenu\\n$fontlines|" \
        -e "s|set gfxmode=[^ ]*|set gfxmode=$RES,auto|" \
        -e '/^[[:space:]]*initrd[[:space:]]/d' \
        -e 's/^([[:space:]]*)(linux|linux16|linuxefi|chainloader)[[:space:]].*/\1gimtest_boot/' \
        "$cfg"
} >"$vmcfg"
grub-script-check "$vmcfg"
cp "$vmcfg" "$OUT/grub.cfg.vm"

# ---- 3. standalone GRUB EFI image with everything in memdisk ----------------
cat >"$W/stub.cfg" <<'EOF'
# Like Ubuntu's /EFI/ubuntu/grub.cfg: load the real grub.cfg with configfile
# (so it runs nested). $prefix stays at the memdisk module directory.
set root=memdisk
configfile ($root)/grub/grub.cfg
EOF
maps=("boot/grub/grub.cfg=$W/stub.cfg" "grub/grub.cfg=$vmcfg"
      "boot/grub/fonts/unicode.pf2=/usr/share/grub/unicode.pf2")
while IFS= read -r f; do
    maps+=("grub/themes/grub-icon-menu/${f#"$THEME"/}=$f")
done < <(find "$THEME" -type f)
mkdir -p "$W/esp/EFI/BOOT"
grub-mkstandalone -O x86_64-efi -o "$W/esp/EFI/BOOT/BOOTX64.EFI" \
    --modules="part_gpt fat normal configfile echo test" "${maps[@]}"

# ---- 4. boot it ----------------------------------------------------------------
cp "$OVMF_VARS" "$W/vars.fd"
accel=(-accel tcg)
if [ -r /dev/kvm ] && [ -w /dev/kvm ]; then accel=(-accel kvm); fi
"${QEMU[@]}" "${accel[@]}" -machine q35 -m 1024 \
    -drive if=pflash,format=raw,unit=0,readonly=on,file="$OVMF_CODE" \
    -drive if=pflash,format=raw,unit=1,file="$W/vars.fd" \
    -drive format=raw,file=fat:rw:"$W/esp" \
    -device VGA,romfile=,xres="${RES%x*}",yres="${RES#*x}" \
    -display none -nic none -no-reboot \
    -monitor unix:"$SOCK",server,nowait \
    -serial file:"$OUT/serial.log" &
QPID=$!

mon() { printf '%s\n' "$1" | socat - UNIX-CONNECT:"$SOCK" >/dev/null; }
for _ in $(seq 50); do [ -S "$SOCK" ] && break; sleep 0.2; done
sleep 0.5
kill -0 "$QPID" 2>/dev/null || { echo "QEMU failed to start" >&2; exit 1; }

for a in "${ACTIONS[@]}"; do
    case "$a" in
        wait:*) sleep "${a#wait:}" ;;
        shot:*)
            name="${a#shot:}"
            mon "screendump $W/$name.ppm"
            sleep 1
            if command -v magick >/dev/null; then magick "$W/$name.ppm" "$OUT/$name.png"; else convert "$W/$name.ppm" "$OUT/$name.png"; fi
            echo "screenshot: $OUT/$name.png ($(identify -format '%wx%h' "$OUT/$name.png"))" ;;
        *) mon "sendkey $a"; sleep 0.6 ;;
    esac
done
sleep 1
echo "---- serial ----"
tr -d '\r' <"$OUT/serial.log" | grep -a 'GIMTEST' || echo "(no GIMTEST-BOOTED line)"
